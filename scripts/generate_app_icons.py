#!/usr/bin/env python3
"""Generate checked-in app icons from assets/branding/app_icon_source.png.

Covers the Android launcher icons, the in-app logo, and the macOS master icon
(macOS derives its .appiconset sizes from that master at build time, because
`macos/` is generated by `flutter create` and is not committed).

Requires Pillow: python -m pip install Pillow
From the repository root: python scripts/generate_app_icons.py
Normal Flutter / Android builds use the generated files without running this.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageOps


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets/branding/app_icon_source.png"
RES = ROOT / "android/app/src/main/res"
PAPER = (255, 254, 240)
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

# Android masks the central 72dp of a 108dp adaptive layer. Keep the drawing
# at 60dp so circular launchers retain the bookmark and the book/play symbol.
ADAPTIVE_SIZE = 108
ARTWORK_SIZE = 60
VISIBLE_SIZE = 72

# The about page draws the in-app logo at 96dp, so 384px covers 4x DPI with
# headroom to spare. WebP keeps the bundled file an order of magnitude smaller
# than the same picture as a PNG.
LOGO_SIZE = 384
LOGO_QUALITY = 88

# macOS: the icon grid puts the artwork on an 824x824 body inside a 1024x1024
# canvas (100px transparent margin on every side) with a squircle corner radius
# of 22.37%. Keeping the same artwork-to-body ratio as the Android icon is what
# makes the two launchers look like the same app.
MACOS_ICON = ROOT / "assets/branding/app_icon_macos.png"
MACOS_DIR = ROOT / "assets/branding/macos"
MACOS_CANVAS = 1024
MACOS_BODY = 824
MACOS_RADIUS_RATIO = 0.2237

# Sizes Xcode expects in AppIcon.appiconset. build_macos.sh slices the master
# icon into these with `sips`, so only the 1024px master is committed.
MACOS_CONTENTS = """{
  "images" : [
    { "filename" : "icon_16x16.png", "idiom" : "mac", "scale" : "1x", "size" : "16x16" },
    { "filename" : "icon_16x16@2x.png", "idiom" : "mac", "scale" : "2x", "size" : "16x16" },
    { "filename" : "icon_32x32.png", "idiom" : "mac", "scale" : "1x", "size" : "32x32" },
    { "filename" : "icon_32x32@2x.png", "idiom" : "mac", "scale" : "2x", "size" : "32x32" },
    { "filename" : "icon_128x128.png", "idiom" : "mac", "scale" : "1x", "size" : "128x128" },
    { "filename" : "icon_128x128@2x.png", "idiom" : "mac", "scale" : "2x", "size" : "128x128" },
    { "filename" : "icon_256x256.png", "idiom" : "mac", "scale" : "1x", "size" : "256x256" },
    { "filename" : "icon_256x256@2x.png", "idiom" : "mac", "scale" : "2x", "size" : "256x256" },
    { "filename" : "icon_512x512.png", "idiom" : "mac", "scale" : "1x", "size" : "512x512" },
    { "filename" : "icon_512x512@2x.png", "idiom" : "mac", "scale" : "2x", "size" : "512x512" }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
"""


def save_png(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)
    print(f"{path.relative_to(ROOT).as_posix()} ({image.width}x{image.height})")


def save_webp(image: Image.Image, path: Path, *, quality: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Drop the alpha channel: the design master's alpha is fully opaque, and
    # carrying it into WebP only makes the encoder store a 255 plane.
    image.convert("RGB").save(path, "WEBP", quality=quality, method=6)
    print(
        f"{path.relative_to(ROOT).as_posix()} "
        f"({image.width}x{image.height}, q{quality})"
    )


def place_artwork(source: Image.Image, size: int, artwork_size: int,
                  *, transparent: bool = False) -> Image.Image:
    background = (*PAPER, 0 if transparent else 255)
    canvas = Image.new("RGBA", (size, size), background)
    artwork = source.resize((artwork_size, artwork_size), Image.Resampling.LANCZOS)
    offset = (size - artwork_size) // 2
    canvas.alpha_composite(artwork, (offset, offset))
    return canvas


def render_macos_icon(source: Image.Image) -> Image.Image:
    """Draw the 1024px macOS master: same paper and artwork ratio as Android."""
    body = place_artwork(
        source, MACOS_BODY, round(MACOS_BODY * ARTWORK_SIZE / VISIBLE_SIZE))
    mask = Image.new("L", (MACOS_BODY, MACOS_BODY), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, MACOS_BODY - 1, MACOS_BODY - 1),
        radius=round(MACOS_BODY * MACOS_RADIUS_RATIO), fill=255)
    body.putalpha(mask)
    canvas = Image.new("RGBA", (MACOS_CANVAS, MACOS_CANVAS), (0, 0, 0, 0))
    offset = (MACOS_CANVAS - MACOS_BODY) // 2
    canvas.alpha_composite(body, (offset, offset))
    return canvas


def main() -> None:
    with Image.open(SOURCE) as original:
        source = ImageOps.exif_transpose(original).convert("RGBA")
    if source.width != source.height or source.width < 512:
        raise SystemExit("Use a square source image of at least 512x512 pixels.")

    # Legacy and adaptive launchers use the same visible artwork proportions.
    legacy_size = VISIBLE_SIZE * 16
    legacy = place_artwork(source, legacy_size, ARTWORK_SIZE * 16)
    round_legacy = legacy.copy()
    round_mask = Image.new("L", legacy.size, 0)
    ImageDraw.Draw(round_mask).ellipse(
        (0, 0, legacy_size - 1, legacy_size - 1), fill=255)
    round_legacy.putalpha(round_mask)

    for density, scale in DENSITIES.items():
        directory = RES / f"mipmap-{density}"
        size = round(48 * scale)
        save_png(legacy.resize((size, size), Image.Resampling.LANCZOS).convert("RGB"),
                 directory / "ic_launcher.png")
        save_png(round_legacy.resize((size, size), Image.Resampling.LANCZOS),
                 directory / "ic_launcher_round.png")
        foreground = place_artwork(source, round(ADAPTIVE_SIZE * scale),
                                   round(ARTWORK_SIZE * scale), transparent=True)
        save_png(foreground, directory / "ic_launcher_foreground.png")

    adaptive = RES / "mipmap-anydpi-v26"
    adaptive.mkdir(parents=True, exist_ok=True)
    adaptive_xml = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_app_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
'''
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (adaptive / name).write_text(adaptive_xml, encoding="utf-8")

    (RES / "values").mkdir(parents=True, exist_ok=True)
    paper_hex = "#" + "".join(f"{value:02X}" for value in PAPER)
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate_app_icons.py. -->\n'
        f'<resources>\n    <color name="ic_launcher_background">{paper_hex}</color>\n'
        '</resources>\n', encoding="utf-8")

    save_webp(source.resize((LOGO_SIZE, LOGO_SIZE), Image.Resampling.LANCZOS),
              ROOT / "assets/images/app_logo.webp", quality=LOGO_QUALITY)

    save_png(render_macos_icon(source), MACOS_ICON)
    MACOS_DIR.mkdir(parents=True, exist_ok=True)
    contents = MACOS_DIR / "Contents.json"
    contents.write_text(MACOS_CONTENTS, encoding="utf-8")
    print(f"{contents.relative_to(ROOT).as_posix()} (AppIcon manifest)")


if __name__ == "__main__":
    main()
